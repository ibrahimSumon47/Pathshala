import { Buffer } from 'node:buffer';

type InvoiceItem = { title: string; pricePaisa: number };

export type InvoiceInput = {
  invoiceNumber: string;
  orderNumber: string;
  paidAt: string | null;
  status: string;
  studentName: string;
  studentEmail: string;
  items: InvoiceItem[];
  subtotalPaisa: number;
  discountPaisa: number;
  totalPaisa: number;
  provider: string | null;
  couponCode?: string | null;
};

/** PDF base-14 fonts only cover Latin text, so Bangla is replaced by a readable fallback. */
export function asciiSafe(value: string, fallback = 'Course'): string {
  const latin = value
    .normalize('NFKD')
    .replace(/[^\x20-\x7E]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return latin.length > 0 ? latin : fallback;
}

/** Parentheses and backslashes end or escape text in a PDF string. */
function pdfString(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

/** Taka amounts in the invoice are ASCII so any PDF reader can show them. */
function money(paisa: number): string {
  const sign = paisa < 0 ? '-' : '';
  const absolute = Math.abs(paisa);
  return `${sign}BDT ${(absolute / 100).toFixed(2)}`;
}

type Line = { text: string; size: number; bold?: boolean; gap: number };

/**
 * Write a single-page invoice by hand. A PDF library would add a dependency for one
 * document shape, and the structure needed here is small enough to keep exact.
 */
export function buildInvoicePdf(input: InvoiceInput): Buffer {
  const lines: Line[] = [
    { text: 'Pathshala', size: 20, bold: true, gap: 26 },
    { text: 'A place to learn and teach', size: 9, gap: 30 },
    { text: `Invoice ${input.invoiceNumber}`, size: 14, bold: true, gap: 22 },
    { text: `Order ${input.orderNumber}`, size: 10, gap: 14 },
    { text: `Status ${input.status}`, size: 10, gap: 14 },
    { text: `Paid ${input.paidAt ? input.paidAt.slice(0, 10) : '-'}`, size: 10, gap: 26 },
    { text: 'Billed to', size: 11, bold: true, gap: 16 },
    { text: asciiSafe(input.studentName, 'Learner'), size: 10, gap: 14 },
    { text: asciiSafe(input.studentEmail, 'learner@example.com'), size: 10, gap: 26 },
    { text: 'Item', size: 10, bold: true, gap: 16 },
  ];

  for (const item of input.items) {
    lines.push({ text: `${asciiSafe(item.title)}  ${money(item.pricePaisa)}`, size: 10, gap: 15 });
  }

  lines.push(
    { text: '', size: 10, gap: 10 },
    { text: `Subtotal  ${money(input.subtotalPaisa)}`, size: 10, gap: 15 },
    {
      text: `Discount${input.couponCode ? ` (${asciiSafe(input.couponCode)})` : ''}  -${money(input.discountPaisa)}`,
      size: 10,
      gap: 15,
    },
    { text: `Total  ${money(input.totalPaisa)}`, size: 12, bold: true, gap: 26 },
    { text: `Paid via ${asciiSafe(input.provider ?? 'test gateway', 'test gateway')}`, size: 9, gap: 14 },
    { text: 'Test mode: no real money was charged.', size: 9, bold: true, gap: 14 },
    { text: 'This invoice is generated by Pathshala for a sandbox order.', size: 9, gap: 14 },
  );

  let cursor = 790;
  const body = lines
    .map((line) => {
      const font = line.bold ? '/F2' : '/F1';
      const text = line.text ? `(${pdfString(line.text)}) Tj` : '';
      const chunk = text ? `BT ${font} ${line.size} Tf 50 ${cursor} Td ${text} ET\n` : '';
      cursor -= line.gap;
      return chunk;
    })
    .join('');

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
    `<< /Length ${Buffer.byteLength(body, 'latin1')} >>\nstream\n${body}endstream`,
  ];

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((object, index) => {
    offsets.push(Buffer.byteLength(pdf, 'latin1'));
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });

  const xrefOffset = Buffer.byteLength(pdf, 'latin1');
  const pad = (value: number) => String(value).padStart(10, '0');
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) pdf += `${pad(offset)} 00000 n \n`;
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  return Buffer.from(pdf, 'latin1');
}

/** A stable, human-readable invoice number derived from an order receipt. */
export function invoiceNumberFor(receiptNumber: string | null, orderNumber: string): string {
  const source = receiptNumber ?? orderNumber;
  return `INV-${source.replace(/[^A-Za-z0-9]/g, '').toUpperCase()}`;
}
